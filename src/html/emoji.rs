#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_aliases_resolve() {
        assert_eq!(value("smile"), Some("😄"));
        assert_eq!(value("+1"), Some("👍"));
        assert_eq!(value("rocket"), Some("🚀"));
    }

    #[test]
    fn unknown_aliases_are_reported_as_missing() {
        assert_eq!(value("nope"), None);
        assert_eq!(value("30"), None);
        assert_eq!(value("Smile"), None);
    }
}
